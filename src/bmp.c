void draw_char(int x, int y, char ch, int color, int bg)
{
    int idx;
    if (ch >= '0' && ch <= '9') idx = ch - '0';
    else if (ch >= 'A' && ch <= 'Z') idx = ch - 'A' + 10;
    else if (ch == ' ') return;
    else return;

    for (int row = 0; row < 16; row++) {
        for (int col = 0; col < 8; col++) {
            int px = x + col, py = y + row;
            if (px < 0 || px >= 800 || py < 0 || py >= 480) continue;
            if (font8x16[idx][row] & (1 << (7 - col))) {
                fbuf[py * 800 + px] = color;
            } else if (bg != -1) {
                fbuf[py * 800 + px] = bg;
            }
        }
    }
}

void draw_str(int x, int y, char *str, int color, int bg)
{
    int cx = x;
    for (int i = 0; str[i]; i++) {
        if (str[i] == ' ') { cx += 8; continue; }
        draw_char(cx, y, str[i], color, bg);
        cx += 10;
    }
}

void draw_btn(int x, int y, int w, int h, int border, int fill, char *text, int text_color)
{
    for (int row = y; row < y + h && row < 480; row++) {
        for (int col = x; col < x + w && col < 800; col++) {
            if (row < 0 || col < 0) continue;
            if (row >= y + 2 && row < y + h - 2 && col >= x + 2 && col < x + w - 2) {
                fbuf[row * 800 + col] = fill;
            } else {
                fbuf[row * 800 + col] = border;
            }
        }
    }
    if (text) {
        int tw = strlen(text) * 10;
        int tx = x + (w - tw) / 2;
        int ty = y + (h - 16) / 2;
        draw_str(tx, ty, text, text_color, fill);
    }
}