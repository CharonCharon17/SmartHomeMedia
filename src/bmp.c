extern int *fbuf;

int showbmp(const char *path)
{
    int fd = open(path, O_RDONLY);
    if (fd < 0) return -1;

    unsigned char hdr[54];
    read(fd, hdr, 54);
    lseek(fd, 54, SEEK_SET);

    int iw = *(int *)&hdr[18];
    int ih = *(int *)&hdr[22];
    if (ih < 0) ih = -ih;

    int bpp = *(short *)&hdr[28];
    int pb = bpp / 8;
    int rs = ((iw * pb + 3) / 4) * 4;
    int ds = rs * ih;

    unsigned char *data = malloc(ds);
    if (!data) { close(fd); return -1; }

    read(fd, data, ds);

    int sx = (W - iw) / 2;
    int sy = (H - ih) / 2;

    for (int y = 0; y < ih && y + sy < H; y++) {
        for (int x = 0; x < iw && x + sx < W; x++) {
            int si = (ih - 1 - y) * rs + x * pb;
            int di = (y + sy) * W + (x + sx);
            int b = data[si];
            int g = data[si + 1];
            int r = data[si + 2];
            fbuf[di] = (r << 16) | (g << 8) | b;
        }
    }

    free(data);
    close(fd);
    return 0;
}

